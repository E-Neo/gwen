//! `gwen update`: refresh a project's template-owned files from `GWEN_HOME`.
//!
//! Project content is never touched: `slides/`, `[[sections]]`, the
//! `[presentation]` table (title, author, size) and the project's own named
//! styles stay as they are. Everything the template owns - `masters/`,
//! `media/`, the extra skills under `.agents/` - is synced, and the template's
//! `[theme]` / `[styles.*]` values are merged into `main.toml` key by key, so
//! comments, key order and project-only keys survive.

use std::collections::BTreeSet;
use std::path::{Path, PathBuf};

use gwen::error::Result;
use toml_edit::{DocumentMut, Item, Key, Table};

use crate::scaffold;

/// Template-owned trees, relative to both the template and the project.
const TREES: [&str; 3] = ["masters", "media", ".agents"];

/// The `gwen` skill is generated by the binary, never copied from the
/// template (the installed gwen may be newer than the template).
const RESERVED: &str = ".agents/skills/gwen";

/// Sync `project` with the installed template.
pub fn update(project: &str, dry_run: bool, keep_styles: bool) -> Result<()> {
    let root = Path::new(project);
    if !root.join("main.toml").is_file() {
        return Err(miette::miette!(
            "`{}` is not a gwen project (no `main.toml`)",
            root.display()
        ));
    }
    let template = scaffold::template_dir().ok_or_else(|| {
        miette::miette!(
            "no template found in the gwen home (set GWEN_HOME, or create `~/.gwen/template`)"
        )
    })?;
    if same_dir(root, &template) {
        return Err(miette::miette!(
            "`{}` is the template itself; `gwen update` only updates projects",
            root.display()
        ));
    }

    let mut report = Report::default();
    // Parse and merge `main.toml` up front so a broken project fails before
    // any file is written.
    let merged = if keep_styles {
        None
    } else {
        merged_main(root, &template)?
    };

    let files = template_files(&template)?;
    for (rel, src) in &files {
        let bytes = std::fs::read(src)
            .map_err(|e| miette::miette!("cannot read `{}`: {e}", src.display()))?;
        sync(root, rel, &bytes, None, dry_run, &mut report)?;
    }

    // The project skill comes from this binary, not from the template.
    for (rel, contents) in scaffold::gwen_skill_files() {
        sync(
            root,
            Path::new(rel),
            contents.as_bytes(),
            None,
            dry_run,
            &mut report,
        )?;
    }

    match merged {
        Some((contents, detail)) => sync(
            root,
            Path::new("main.toml"),
            contents.as_bytes(),
            detail.as_deref(),
            dry_run,
            &mut report,
        )?,
        None if keep_styles => {}
        None => report.unchanged += 1,
    }

    if gitignore_stale(root) {
        let rel = Path::new(".gitignore");
        let (action, paths) = if root.join(rel).exists() {
            ("update", &mut report.updated)
        } else {
            ("create", &mut report.created)
        };
        paths.push(rel.to_path_buf());
        print_change(action, rel, None, dry_run);
        if !dry_run {
            scaffold::write_gitignore(root)?;
        }
    }

    // Files the project still has but the template no longer ships. Never
    // deleted: a slide or master may still reference them.
    let known: BTreeSet<&Path> = files.iter().map(|(rel, _)| rel.as_path()).collect();
    for tree in TREES {
        let dir = root.join(tree);
        if !dir.is_dir() {
            continue;
        }
        for rel in walk(&dir)? {
            let rel = Path::new(tree).join(rel);
            if rel.starts_with(RESERVED) || known.contains(rel.as_path()) {
                continue;
            }
            report.stale.push(rel);
        }
    }

    print_summary(&report, dry_run);
    Ok(())
}

#[derive(Default)]
struct Report {
    created: Vec<PathBuf>,
    updated: Vec<PathBuf>,
    unchanged: usize,
    stale: Vec<PathBuf>,
}

/// Every file the template owns, as `(path relative to the project, source)`.
fn template_files(template: &Path) -> Result<Vec<(PathBuf, PathBuf)>> {
    let mut out = Vec::new();
    for tree in TREES {
        let dir = template.join(tree);
        if !dir.is_dir() {
            continue;
        }
        for rel in walk(&dir)? {
            if tree == ".agents" && rel.starts_with("skills/gwen") {
                continue;
            }
            out.push((Path::new(tree).join(&rel), dir.join(&rel)));
        }
    }
    Ok(out)
}

/// All files below `dir`, as paths relative to `dir`, sorted.
fn walk(dir: &Path) -> Result<Vec<PathBuf>> {
    fn rec(dir: &Path, base: &Path, out: &mut Vec<PathBuf>) -> Result<()> {
        let entries = std::fs::read_dir(dir)
            .map_err(|e| miette::miette!("cannot list `{}`: {e}", dir.display()))?;
        for entry in entries {
            let entry =
                entry.map_err(|e| miette::miette!("cannot read `{}`: {e}", dir.display()))?;
            let path = entry.path();
            let rel = path
                .strip_prefix(base)
                .map(Path::to_path_buf)
                .unwrap_or_else(|_| path.clone());
            let kind = entry
                .file_type()
                .map_err(|e| miette::miette!("cannot stat `{}`: {e}", path.display()))?;
            if kind.is_dir() {
                rec(&path, base, out)?;
            } else {
                out.push(rel);
            }
        }
        Ok(())
    }
    let mut out = Vec::new();
    rec(dir, dir, &mut out)?;
    out.sort();
    Ok(out)
}

/// Write `bytes` to `root/rel` unless it already matches. Reports the change
/// and, when overwriting, keeps the previous contents under
/// `target/update-backup/`.
fn sync(
    root: &Path,
    rel: &Path,
    bytes: &[u8],
    detail: Option<&str>,
    dry_run: bool,
    report: &mut Report,
) -> Result<()> {
    let path = root.join(rel);
    match std::fs::read(&path) {
        Ok(old) if old == bytes => {
            report.unchanged += 1;
            Ok(())
        }
        Ok(old) => {
            report.updated.push(rel.to_path_buf());
            print_change("update", rel, detail, dry_run);
            if !dry_run {
                backup(root, rel, &old)?;
                write_bytes(&path, bytes)?;
            }
            Ok(())
        }
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => {
            report.created.push(rel.to_path_buf());
            print_change("create", rel, detail, dry_run);
            if !dry_run {
                write_bytes(&path, bytes)?;
            }
            Ok(())
        }
        Err(e) => Err(miette::miette!("cannot read `{}`: {e}", path.display())),
    }
}

fn backup(root: &Path, rel: &Path, bytes: &[u8]) -> Result<()> {
    let path = root.join("target").join("update-backup").join(rel);
    write_bytes(&path, bytes)
}

fn write_bytes(path: &Path, bytes: &[u8]) -> Result<()> {
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent)
            .map_err(|e| miette::miette!("cannot create `{}`: {e}", parent.display()))?;
    }
    std::fs::write(path, bytes)
        .map_err(|e| miette::miette!("cannot write `{}`: {e}", path.display()))
}

fn print_change(what: &str, rel: &Path, detail: Option<&str>, dry_run: bool) {
    let what = if dry_run {
        format!("would {what}")
    } else {
        what.to_string()
    };
    match detail {
        Some(detail) => eprintln!("{what:<13} {} ({detail})", rel.display()),
        None => eprintln!("{what:<13} {}", rel.display()),
    }
}

fn print_summary(report: &Report, dry_run: bool) {
    for rel in &report.stale {
        eprintln!(
            "{:<13} {} (not in template, left in place)",
            "stale",
            rel.display()
        );
    }
    if report.created.is_empty() && report.updated.is_empty() && report.stale.is_empty() {
        eprintln!("already up to date");
        return;
    }
    let mut summary = format!(
        "{} updated, {} created, {} unchanged",
        report.updated.len(),
        report.created.len(),
        report.unchanged
    );
    if !report.stale.is_empty() {
        summary.push_str(&format!(", {} stale", report.stale.len()));
    }
    eprintln!("{summary}");
    if dry_run {
        eprintln!("dry run: nothing written");
    }
}

fn gitignore_stale(root: &Path) -> bool {
    match std::fs::read_to_string(root.join(".gitignore")) {
        Ok(contents) => !contents.lines().any(|line| line.trim() == "target/"),
        Err(_) => true,
    }
}

/// Merge the template's `[theme]` and `[styles.*]` into the project's
/// `main.toml`, leaving `[presentation]`, `[[sections]]` and every comment
/// intact. Values are merged key by key; a table is recursed into so its
/// header comment stays where it is. Returns the merged file (and the changed
/// paths, for the report) only when something differs.
fn merged_main(root: &Path, template: &Path) -> Result<Option<(String, Option<String>)>> {
    let project_path = root.join("main.toml");
    let template_path = template.join("main.toml");
    let src = std::fs::read_to_string(&project_path)
        .map_err(|e| miette::miette!("cannot read `{}`: {e}", project_path.display()))?;
    let tpl = std::fs::read_to_string(&template_path)
        .map_err(|e| miette::miette!("cannot read `{}`: {e}", template_path.display()))?;
    let mut doc: DocumentMut = src
        .parse()
        .map_err(|e| miette::miette!("`{}`: {e}", project_path.display()))?;
    let tpl: DocumentMut = tpl
        .parse()
        .map_err(|e| miette::miette!("`{}`: {e}", template_path.display()))?;

    let mut changed = Vec::new();
    for key in ["theme", "styles"] {
        let Some((tpl_key, tpl_item)) = tpl.as_table().get_key_value(key) else {
            continue;
        };
        merge_item(
            doc.as_table_mut(),
            key,
            tpl_key,
            tpl_item,
            key,
            &mut changed,
        );
    }

    let out = doc.to_string();
    if out == src {
        return Ok(None);
    }
    let detail = (!changed.is_empty()).then(|| changed.join(", "));
    Ok(Some((out, detail)))
}

fn merge_item(
    dst: &mut Table,
    key: &str,
    src_key: &Key,
    src: &Item,
    path: &str,
    changed: &mut Vec<String>,
) {
    match dst.get_mut(key) {
        Some(dst_item) if dst_item.is_table() && src.is_table() => {
            merge_table(
                dst_item.as_table_mut().expect("checked above"),
                src.as_table().expect("checked above"),
                path,
                changed,
            );
        }
        Some(dst_item) => {
            if dst_item.to_string() != src.to_string() {
                replace_value(dst_item, src);
                changed.push(path.to_string());
            }
        }
        None => {
            dst.insert_formatted(src_key, src.clone());
            changed.push(path.to_string());
        }
    }
}

fn merge_table(dst: &mut Table, src: &Table, base: &str, changed: &mut Vec<String>) {
    for (key, src_item) in src.iter() {
        let Some((src_key, _)) = src.get_key_value(key) else {
            continue;
        };
        let path = format!("{base}.{key}");
        merge_item(dst, key, src_key, src_item, &path, changed);
    }
}

/// Replace a value while keeping the destination's decor (the comment on the
/// key line and any trailing comment).
fn replace_value(dst: &mut Item, src: &Item) {
    let decor = dst.as_value().map(|value| value.decor().clone());
    let mut new = src.clone();
    if let (Some(decor), Some(value)) = (decor, new.as_value_mut()) {
        *value.decor_mut() = decor;
    }
    *dst = new;
}

fn same_dir(a: &Path, b: &Path) -> bool {
    match (a.canonicalize(), b.canonicalize()) {
        (Ok(a), Ok(b)) => a == b,
        _ => false,
    }
}
